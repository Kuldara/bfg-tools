# -*- coding: utf-8 -*-
"""Fetches the apps' fonts once and writes them into CSS as base64.

Without this a page would fetch its fonts from Google Fonts. That means three
things neither way of using the tools needs: a request to a third party that
sees the user's IP address, a dependency on the network when the file is meant
to work without one, and another font for those whose request fails - which
changes a card measured in millimetres from one machine to the next.

Only the latin and latin-ext subsets are kept. Cyrillic and Greek would triple
the size and are not used.

Output: fonts.css, which the builds embed (apps/*/build.js).

Run when the fonts change:  python packages/ui/make_fonts.py
"""
import base64
import io
import os
import re
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "fonts.css")

# The same request as a page's <link> tag would make.
CSS_URL = ("https://fonts.googleapis.com/css2"
           "?family=Archivo+Narrow:wght@500;600;700"
           "&family=IBM+Plex+Mono:wght@400;500;600"
           "&family=IBM+Plex+Sans:wght@400;500;600"
           "&display=swap")

# A Chrome user agent, so Google returns woff2 and not an older format.
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")

KEEP = ("latin",)

# Unused cuts dropped, checked against the apps' CSS: Archivo Narrow is used
# only at weights 600 and 700.
SKIP = {("Archivo Narrow", "500")}


def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=45) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


css = get(CSS_URL)

# Blocks of the form:  /* latin */\n@font-face { ... }
blocks = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{.*?\})",
                    css, re.S)
assert blocks, "no @font-face blocks were found in the Google Fonts response"

out, kept, total = [], 0, 0
out.append("/* Fonts embedded so the file needs no network and renders the")
out.append("   same on every machine. Generated by make_fonts.py from")
out.append("   Google Fonts; latin and latin-ext subsets only. */")

for subset, block in blocks:
    total += 1
    if subset not in KEEP:
        continue
    m = re.search(r"src:\s*url\((https://[^)]+\.woff2)\)", block)
    if not m:
        continue
    fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    wgt = re.search(r"font-weight:\s*(\d+)", block).group(1)
    if (fam, wgt) in SKIP:
        continue
    raw = get(m.group(1), binary=True)
    b64 = base64.b64encode(raw).decode("ascii")
    # unicode-range is kept: a browser loads only the blocks it needs, and
    # with a data URI it still limits what it uses.
    ur = re.search(r"unicode-range:\s*([^;]+);", block)
    rule = ["@font-face{font-family:'%s';font-style:normal;"
            "font-weight:%s;font-display:swap;" % (fam, wgt),
            "src:url(data:font/woff2;charset=utf-8;base64,%s) "
            "format('woff2');" % b64]
    if ur:
        rule.append("unicode-range:%s;" % ur.group(1).strip())
    rule.append("}")
    out.append("".join(rule))
    kept += 1
    print("  %-18s %-4s %-10s %6.1f kB" % (fam, wgt, subset, len(raw) / 1024))

text = "\n".join(out) + "\n"
io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
assert all(ord(c) < 128 for c in text), "non-ASCII characters"
print()
print("blocks %d, kept %d" % (total, kept))
print("%s  %.0f kB" % (OUT, len(text) / 1024))
