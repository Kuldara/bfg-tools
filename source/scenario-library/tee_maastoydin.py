# -*- coding: utf-8 -*-
"""Battlezone Generatorin arvontaydin Scenario Libraryyn (21.10.2026).

Ytimen ainoa lähde on ../terrain generator/index.html, BZCORE-merkkien välissä:
nopat, battlezone-taulukot, geometria, generate() ja sääntötekstit (RULES,
EVENT_RULES). Tämä skripti kirjoittaa siitä tiedoston battlezone-core.js, jossa
sama teksti on tavulleen sellaisenaan IIFE:n sisällä nimiavaruutena BZ (kirjaston
globaalit nimet eivät törmää ytimen nimiin).

    python tee_maastoydin.py           kirjoittaa battlezone-core.js, jos se on muuttunut
    python tee_maastoydin.py --tarkista  vain tarkistus: paluuarvo 1, jos kopio on vanha

ÄLÄ muokkaa battlezone-core.js:ää käsin. testit/maastotesti.js ja
julkaisu/kokoa.py kaatuvat, jos kopio ja lähde eroavat.
"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "terrain generator", "index.html")
DST = os.path.join(HERE, "battlezone-core.js")
OPEN, CLOSE = "/*BZCORE*/", "/*/BZCORE*/"
NAMES = ["makeRng", "Dice", "PLANET_SUB", "ZONES", "SUN_EDGE", "PLANET_BAND", "KIND", "KEEP_CLEAR",
         "RING_ON", "extents", "overlaps", "onTable", "generate", "RULES", "EVENT_RULES"]


def core_text(src_text):
    a, b = src_text.count(OPEN), src_text.count(CLOSE)
    assert a == 1 and b == 1, "terrain generator/index.html: BZCORE-merkit %d/%d, pitää olla 1/1" % (a, b)
    i, j = src_text.index(OPEN) + len(OPEN), src_text.index(CLOSE)
    assert i < j
    return src_text[i:j].replace("\r\n", "\n")


def build(src_text):
    core = core_text(src_text)
    for n in NAMES:
        assert ("function " + n + "(") in core or ("const " + n + " ") in core, "ytimestä puuttuu " + n
    return ("/* GENERATED by tee_maastoydin.py from ../terrain generator/index.html (BZCORE).\n"
            "   Do not edit: change the generator and run the script. The text between the\n"
            "   markers below is the generator's own, byte for byte. */\n"
            "const BZ = (function () {\n'use strict';\n" + OPEN + core + CLOSE + "\n"
            "return { " + ", ".join(NAMES) + " };\n})();\n")


def main():
    src = io.open(SRC, encoding="utf-8", newline="").read()
    want = build(src)
    have = io.open(DST, encoding="utf-8", newline="").read() if os.path.exists(DST) else None
    if "--tarkista" in sys.argv:
        if have != want:
            print("battlezone-core.js on VANHA: aja python tee_maastoydin.py")
            return 1
        print("battlezone-core.js ajan tasalla")
        return 0
    if have == want:
        print("battlezone-core.js ajan tasalla")
        return 0
    tmp = DST + ".tmp"
    io.open(tmp, "w", encoding="utf-8", newline="").write(want)
    os.replace(tmp, DST)
    print("battlezone-core.js kirjoitettu (%d merkkiä)" % len(want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
