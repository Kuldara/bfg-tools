# -*- coding: utf-8 -*-
"""Hakee sovelluksen kirjasimet ja kirjoittaa ne base64-muodossa CSS:ksi.

Ilman tata sovellus hakee fontit Google Fontsista. Se tarkoittaa kolmea
asiaa joita kumpikaan kayttotapa ei tarvitse: pyynto kolmannelle
osapuolelle joka nakee kayttajan IP:n, riippuvuus verkosta silloin kun
tiedosto on tarkoitus toimia ilman sita, ja eri kirjasin niille joilla
pyynto epaonnistuu - mika muuttaa millimetreissa mitoitetun kortin
ulkoasua koneelta toiselle.

Vain latin ja latin-ext otetaan mukaan. Kyrilliset ja kreikkalaiset
osajoukot kolminkertaistaisivat koon eika niita kayteta.

Tulos: fonts_inline.css, jonka build.py upottaa tiedostoon.

Aja tassa kansiossa kun kirjasimet vaihtuvat:  python make_fonts.py
"""
import base64
import io
import os
import re
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "fonts_inline.css")

# Sama pyynto kuin sovelluksen <link>-tagissa.
CSS_URL = ("https://fonts.googleapis.com/css2"
           "?family=Archivo+Narrow:wght@500;600;700"
           "&family=IBM+Plex+Mono:wght@400;500;600"
           "&family=IBM+Plex+Sans:wght@400;500;600"
           "&display=swap")

# Chrome-tunniste, jotta Google palauttaa woff2:n eika vanhaa formaattia.
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")

KEEP = ("latin",)

# Kayttamattomat leikkaukset pois. Kaytto tarkistettu sovelluksen CSS:sta:
# Archivo Narrow esiintyy vain painoilla 600 ja 700.
SKIP = {("Archivo Narrow", "500")}


def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=45) as r:
        data = r.read()
    return data if binary else data.decode("utf-8")


css = get(CSS_URL)

# Lohkot muotoa:  /* latin */\n@font-face { ... }
blocks = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{.*?\})",
                    css, re.S)
assert blocks, "Google Fontsin vastauksesta ei loytynyt @font-face-lohkoja"

out, kept, total = [], 0, 0
out.append("/* Fonts embedded so the file needs no network and renders the")
out.append("   same on every machine. Generated by make_fonts.py from")
out.append("   Google Fonts; latin and latin-ext subsets only. */")

for subset, block in blocks:
    total += 1
    if subset not in KEEP:
        continue
    m = re.search(r"src:\s*url\((https://[^)]+\.woff2)\)", block)
    if not m:
        continue
    fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    wgt = re.search(r"font-weight:\s*(\d+)", block).group(1)
    if (fam, wgt) in SKIP:
        continue
    raw = get(m.group(1), binary=True)
    b64 = base64.b64encode(raw).decode("ascii")
    # unicode-range sailytetaan: selain lataa vain tarvitsemansa lohkot,
    # ja data-URI:lla se rajaa myos mita se kayttaa.
    ur = re.search(r"unicode-range:\s*([^;]+);", block)
    rule = ["@font-face{font-family:'%s';font-style:normal;"
            "font-weight:%s;font-display:swap;" % (fam, wgt),
            "src:url(data:font/woff2;charset=utf-8;base64,%s) "
            "format('woff2');" % b64]
    if ur:
        rule.append("unicode-range:%s;" % ur.group(1).strip())
    rule.append("}")
    out.append("".join(rule))
    kept += 1
    print("  %-18s %-4s %-10s %6.1f kB" % (fam, wgt, subset, len(raw) / 1024))

text = "\n".join(out) + "\n"
io.open(OUT, "w", encoding="utf-8").write(text)
assert all(ord(c) < 128 for c in text), "ei-ASCII merkkeja"
print()
print("lohkoja %d, mukaan otettu %d" % (total, kept))
print("%s  %.0f kB" % (OUT, len(text) / 1024))
